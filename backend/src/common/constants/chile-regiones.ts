function normalizar(texto: string): string {
  return texto.normalize('NFD').replace(/[̀-ͯ]/g, '').trim().toLowerCase();
}

/**
 * Resuelve región + comuna contra el catálogo, tolerando mayúsculas, tildes, ñ y espacios
 * de sobra ("nunoa " → "Ñuñoa"). Devuelve los nombres canónicos, o null si la comuna no
 * pertenece a esa región.
 */
export function resolverComuna(region: string, comuna: string): { region: string; comuna: string } | null {
  const regionEncontrada = REGIONES_CHILE.find((r) => normalizar(r.region) === normalizar(region));
  if (!regionEncontrada) {
    return null;
  }
  const comunaEncontrada = regionEncontrada.comunas.find((c) => normalizar(c) === normalizar(comuna));
  return comunaEncontrada ? { region: regionEncontrada.region, comuna: comunaEncontrada } : null;
}
